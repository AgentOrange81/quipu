"""`quipu brief` — the standing answer an agent boots with, instead of a search it has to think of (#51).

The problem this solves is not retrieval quality, it is *startup*. A vault of 860 entries answers any
single question well, but an agent that has just woken up does not know which question to ask. Prior art
has a name for the fix (hindsight calls it a mental model: a standing question whose answer is rewritten
as the bank learns, read as a database read with no retrieval and no LLM call), and the shape is simple
enough to build deterministically from what a vault already contains.

So a brief is: promoted entries only, grouped by kind, one line each, with the question the entry answers
and a one-line pointer to the evidence. No model, no ranking, no query — sorting by importance then
recency, which is reproducible and cheap.

Where it is written matters. The brief is DERIVED, like the FTS table and the vectors: it goes under
`.quipu/brief/`, never into `notes/`, because a generated page beside the entries would be ingested as an
entry — the exact self-magnet failure measured on this vault in October (a note that quoted the
questions ranked first for all of them).
"""
from __future__ import annotations

import datetime as _dt

#: One line per entry. Beyond this the brief stops being a boot page and becomes a document nobody reads.
MAX_LINE_CHARS = 200

#: How much evidence to show. Enough to be checkable, short enough to stay one line.
EVIDENCE_CHARS = 110

#: Default number of entries. Measured on the live vault: all 289 promoted entries render 81,819 bytes
#: (~20k tokens), which is a document, not a boot page; 40 renders ~10k bytes (~2.5k tokens), which an
#: agent can actually start with. `--limit 0` means everything, for a human reading it.
DEFAULT_LIMIT = 40

_KIND_ORDER = ("fact", "decision", "conclusion", "lesson", "recipe", "preference", "question")


def _short(text: str, limit: int) -> str:
    text = " ".join((text or "").split())
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


def _kind_rank(kind: str) -> tuple[int, str]:
    try:
        return _KIND_ORDER.index(kind), kind
    except ValueError:
        return len(_KIND_ORDER), kind


def build(entries, project: str = "", agent: str = "", scope: str = "",
          max_lines: int = DEFAULT_LIMIT) -> str:
    """Render the brief for `entries` (any iterable of Entry). Promoted only, deterministic order."""
    picked = [e for e in entries if (e.state or "") == "promoted"]
    if project:
        picked = [e for e in picked if (e.project or "") == project]
    if agent:
        picked = [e for e in picked if (e.agent or "") == agent]
    picked.sort(key=lambda e: (-float(e.importance or 0.0), e.created or "", e.id))
    if max_lines:
        picked = picked[:max_lines]

    label = scope or project or agent or "vault"
    out = [f"# Brief — {label}", ""]
    out.append(f"{len(picked)} promoted "
               f"{'entries' if len(picked) != 1 else 'entry'}, highest importance first. "
               f"Generated by `quipu brief`; do not edit, edit the entries.")
    out.append("")

    grouped: dict[str, list] = {}
    for e in picked:
        grouped.setdefault(e.kind or "fact", []).append(e)

    for kind in sorted(grouped, key=_kind_rank):
        out.append(f"## {kind}")
        out.append("")
        for e in grouped[kind]:
            line = f"- **{_short(e.summary, MAX_LINE_CHARS)}**"
            if (e.ask or "").strip():
                line += f" — answers: {_short(e.ask, MAX_LINE_CHARS)}"
            out.append(line)
            if (e.evidence or "").strip():
                out.append(f"  - evidence: {_short(e.evidence, EVIDENCE_CHARS)}")
            meta = " · ".join(x for x in (e.project, e.created[:10]) if x)
            if meta:
                out.append(f"  - {meta} · `{e.id}`")
        out.append("")
    if not picked:
        out.append("_No promoted entries yet. Promote one with `quipu promote`._")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def stamp() -> str:
    return _dt.datetime.now(_dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def default_relpath(scope: str) -> str:
    safe = "".join(c if c.isalnum() or c in "-_." else "-" for c in (scope or "vault"))[:60]
    return f"brief/{safe}.md"
